def test_api_chat_end_and_analytics_endpoints():
    from fastapi.testclient import TestClient

    client = TestClient(main.app)

    health = client.get("/health").json()
    assert health["status"] == "ok"

    first = client.post("/chat", json={"message": "Hi, I'm looking at a 2 BHK"}).json()
    session_id = first["session_id"]
    assert first["reply"]
    assert first["profile"]["configuration_interest"] == "2BHK"

    second = client.post(
        "/chat", json={"message": "What's the price?", "session_id": session_id}
    ).json()
    assert "one point three five crore" in second["reply"].lower()

    ended = client.post("/end", json={"session_id": session_id}).json()
    assert set(ended["analytics"]) == set(main.SCHEMA_KEYS)

    on_demand = client.get(f"/analytics/{session_id}").json()
    assert on_demand["analytics"]["configuration_interest"] == "2BHK"

    assert client.get("/analytics/nope").status_code == 404
    assert client.get("/").status_code == 200


def test_api_booking_failure_switch():
    from fastapi.testclient import TestClient

    client = TestClient(main.app)
    session_id = "api_fail_demo"
    payloads: List[Dict[str, object]] = [
        {"message": text, "session_id": session_id, "force_booking_failure": True}
        for text in BOOKING_TURNS
    ]
    last = {}
    for payload in payloads:
        last = client.post("/chat", json=payload).json()

    assert last["booking"] is not None
    assert last["booking"]["ok"] is False
    assert last["booking"]["status"] == "booking_failed"
    assert last["profile"]["site_visit_status"] == "booking_failed"
