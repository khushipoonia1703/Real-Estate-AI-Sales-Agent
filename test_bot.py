# Things the agent must never produce. Any of these means it invented a fact.
FORBIDDEN_PATTERNS = (
    r"\bsq\.?\s?ft\b", r"\bsquare feet\b", r"\bcarpet area of\b",
    r"\bpossession (?:is|in|by|on|date is)\b",
    r"\b(?:20\d{2})\b",                      # any year, i.e. an invented date
    r"\b\d+\s?%\s?(?:off|discount)\b",
    r"\bdiscount of\b", r"\bspecial offer\b", r"\blimited period\b",
    r"\bonly \d+ units\b", r"\bunits (?:are )?(?:left|available)\b",
    r"\bRERA\s*(?:no|number|id)\b",
    r"\bEMI (?:of|is|will be|starts)\b",
    r"\b\d+\s?(?:bhk)?\s?(?:sq|sqft)\b",
    # invented neighbourhood claims: distances, travel times, named landmarks
    r"\b\d+(?:\.\d+)?\s?(?:km|kms|kilometre|kilometer|kilometres|kilometers)\b",
    r"\b\d+\s?(?:min|mins|minute|minutes|hour|hours)\s?(?:from|away|to|drive|by road|by car)\b",
    r"\bwalking distance\b",
    r"\bjust \d+\s?(?:min|mins|minutes)\b",
    r"\b(?:metro station|yellow line|rapid metro|dwarka expressway|golf course road)\b",
    r"\bNH-?\s?\d+\b",
)

MARKDOWN_PATTERNS = (r"\*\*", r"^\s*[-*•]\s", r"^#{1,6}\s", r"```", r"\|\s*-{2,}")
EMOJI_RE = re.compile("[\U0001F300-\U0001FAFF\U00002600-\U000027BF]")
DEVANAGARI_RE = re.compile(r"[ऀ-ॿ]")

ALL_REPLIES: List[str] = []
RESULTS: List[Dict[str, object]] = []


@pytest.fixture(autouse=True)
def _clean_state():
    """Every test starts from an empty session store and an empty calendar."""
    main.store.clear()
    main.reset_calendar()
    yield
    main.store.clear()
    main.reset_calendar()


@pytest.fixture(scope="session", autouse=True)
def _scenario_report():
    """Write the input / expected / actual table the brief asks for."""
    yield
    if not RESULTS:
        return
    mode = "live Groq" if LIVE else "deterministic mock"
    lines = [
        "# Scenario report",
        "",
        f"Generated by `pytest`. LLM backend: **{mode}**.",
        "",
    ]
    for item in RESULTS:
        lines.append(f"## {item['id']}")
        lines.append("")
        lines.append("**Input**")
        lines.append("")
        for turn in item["inputs"]:
            lines.append(f"- Customer: {turn}")
        lines.append("")
        lines.append(f"**Expected behaviour** — {item['expected']}")
        lines.append("")
        lines.append("**Actual output**")
        lines.append("")
        for turn in item["actual"]:
            lines.append(f"- Ava: {turn}")
        if item.get("extra"):
            lines.append("")
            lines.append(f"**Also asserted** — {item['extra']}")
        lines.append("")
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")


def run_scenario(
    scenario_id: str,
    inputs: List[str],
    expected: str,
    *,
    force_booking_failure: bool = False,
    extra: str = "",
) -> Tuple[Session, List[str]]:
    """Play a conversation and record it for the report."""
    session = main.store.get_or_create(scenario_id)
    session.force_booking_failure = force_booking_failure
    replies: List[str] = []
    for message in inputs:
        replies.append(main.handle_turn(session, message).reply)
    ALL_REPLIES.extend(replies)
    RESULTS.append(
        {
            "id": scenario_id,
            "inputs": inputs,
            "expected": expected,
            "actual": replies,
            "extra": extra,
        }
    )
    return session, replies


def assert_voice_safe(reply: str) -> None:
    """The style contract: no markup, no emoji, one question, short."""
    for pattern in MARKDOWN_PATTERNS:
        assert not re.search(pattern, reply, re.MULTILINE), f"markdown in reply: {reply!r}"
    assert not EMOJI_RE.search(reply), f"emoji in reply: {reply!r}"
    assert "[[" not in reply, f"control token leaked to customer: {reply!r}"
    assert "{" not in reply and '":' not in reply, f"structured data in reply: {reply!r}"
    assert reply.count("?") <= 1, f"more than one question in a turn: {reply!r}"
    assert len(reply.split()) <= 70, f"reply too long for voice: {reply!r}"


def assert_no_fabrication(reply: str) -> None:
    for pattern in FORBIDDEN_PATTERNS:
        assert not re.search(pattern, reply, re.IGNORECASE), (
            f"invented fact matching {pattern!r} in: {reply!r}"
        )


def looks_hinglish_or_hindi(reply: str) -> bool:
    if DEVANAGARI_RE.search(reply):
        return True
    markers = (
        "aap", "hai", "hain", "kya", "nahi", "mein", "karun", "karna", "theek",
        "bilkul", "shukriya", "dekh", "rahe", "liye", "main", "ke", "ki",
    )
    words = set(re.findall(r"[a-z]+", reply.lower()))
    return len(words & set(markers)) >= 2


