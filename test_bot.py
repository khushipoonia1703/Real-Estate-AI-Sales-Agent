"""Scenario tests: input -> expected behaviour -> actual output.

Every situation the brief requires has a case here. Assertions are on
*behavioural properties* (did it refuse to invent a number, did it mirror the
language, did it avoid claiming a failed booking worked) rather than on exact
strings, so they survive rewording of the prompt and hold for a live model too.

Run offline:  LLM_MOCK=1 pytest -q      (default; no key needed)
Run live:     LIVE_TESTS=1 GROQ_API_KEY=... pytest -q

Each scenario appends its input, expectation and actual output to
`scenario_report.md`, written when the run finishes.
"""

